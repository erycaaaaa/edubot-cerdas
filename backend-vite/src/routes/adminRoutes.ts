import { Router } from 'express';
import { requireAuth, requireRole } from '../middleware/auth';
import { adminHandler } from '../controllers/adminController';
const router = Router();
router.use(requireAuth, requireRole('admin'));
router.get('/schools', adminHandler('schools'));
router.post('/schools', adminHandler('school_create'));
router.patch('/schools/:schoolId', adminHandler('school_update'));
router.get('/teachers', adminHandler('teachers'));
router.post('/teachers/invite', adminHandler('invite'));
router.patch('/teachers/:teacherId/school', adminHandler('teacher_school'));
router.patch('/teachers/:teacherId/status', adminHandler('teacher_status'));
export default router;
